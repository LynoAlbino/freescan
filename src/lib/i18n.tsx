export type Locale = "en" | "he";
const Context = createContext<{ locale: Locale; t: (key: string) => string }>({
  locale: "en",
  t: (s) => s,
});
export function I18n({
  locale,
  children,
}: {
  locale: Locale;
  children: ReactNode;
}) {
  const value = useMemo(
    () => ({
      locale,
      t: (s: string) => (locale === "he" ? he[s] || hebrewCopy[s] || s : s),
    }),
    [locale],
  );
  return <Context.Provider value={value}>{children}</Context.Provider>;
}
export const useI18n = () => useContext(Context);
